"""Инициализация Flask-приложения «Труды учёных».

Используется фабричный паттерн: функция ``create_app()`` создаёт
и настраивает экземпляр приложения. Это позволяет легко создавать
несколько экземпляров (например, для тестов) и подключать разные
конфигурации в будущем.
"""

from flask import Flask


def create_app() -> Flask:
    """Создаёт и настраивает экземпляр Flask-приложения."""
    app = Flask(__name__)

    # Регистрация маршрутов (Blueprint "main" определён в routes.py)
    from . import routes
    app.register_blueprint(routes.bp)

    return app